export function spriteRows(spriteId: string): SpriteRows {
  return SPRITES[spriteId] ?? PLACEHOLDER;
}

export function hasSprite(spriteId: string): boolean {
  return spriteId in SPRITES;
}

export interface DrawSpriteOptions {
  x: number;
  y: number;
  scale: number;
  /** Draws only the outline colours, used for locked or inactive states. */
  dimmed?: boolean;
}

/** Draws one sprite onto a canvas at integer scale. */
export function drawSprite(
  context: CanvasRenderingContext2D,
  spriteId: string,
  options: DrawSpriteOptions,
): void {
  const rows = spriteRows(spriteId);
  const scale = Math.max(1, Math.floor(options.scale));

  for (let row = 0; row < rows.length; row += 1) {
    const line = rows[row];

    for (let column = 0; column < line.length; column += 1) {
      const pixel = line[column] as SpritePixel;

      if (pixel === ".") {
        continue;
      }

      context.fillStyle = options.dimmed
        ? SPRITE_COLORS_DIMMED[pixel]
        : SPRITE_COLORS[pixel];
      context.fillRect(
        options.x + column * scale,
        options.y + row * scale,
        scale,
        scale,
      );
    }
  }
}
