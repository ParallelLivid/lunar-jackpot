/**
 * Pixel-art source data.
 *
 * Every sprite uses the same 12x12 grid so integer scaling keeps edges crisp.
 * The palette is black, white, and two greys, matching the monochrome art
 * direction. A missing sprite falls back to a labelled placeholder rather than
 * breaking the surrounding control.
 */

